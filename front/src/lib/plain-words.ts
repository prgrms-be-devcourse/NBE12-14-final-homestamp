// 경과(행동 기록)를 보여 줄 때만 쓰는 쉬운 말(요구사항명세 부록 A '사용자 말 표').
// 저장된 행동 기록 문장은 바꾸지 않아요. 화면에 그릴 때만 바꾸고, 원문은 title로 그대로 볼 수 있어요.
const WORDS: [RegExp, string][] = [
  [/ · 본 모습 (\d+)번/g, " · $1번째 내용을 보고 확인"],
  [/처리 완료\(양측 확인\)/g, "둘 다 끝났다고 확인했어요"],
  [/양측 확인/g, "둘 다 확인"],
  [/상대 미확인/g, "답하지 않았어요"],
  [/링크 열람/g, "링크로 봤어요"],
  [/합의 대기/g, "답을 기다려요"],
  [/합의됨/g, "합의했어요"],
  [/부담 역제안/g, "다른 안 제안"],
  [/역제안/g, "다른 안 제안"],
  [/응답 요청/g, "확인 요청"],
  [/하자 인정/g, "하자가 있었다고 확인"],
  [/정정 요청/g, "고치기 요청"],
  [/정정/g, "고치기"],
  [/단독 기록/g, "혼자 남긴 기록"],
  [/고친 내용 남김/g, "고친 내용을 남겼어요"],
  [/고친 내용 거둠/g, "고친 내용을 거뒀어요"],
  [/고친 내용 거절/g, "고친 내용을 거절했어요"],
  [/고친 내용 확인/g, "고친 내용을 확인했어요"],
]
export function plainText(text: string) {
  return WORDS.reduce((t, [from, to]) => t.replace(from, to), text)
}
