// 상태 꼬리표와 경과(행동 기록)를 화면에 그릴 때 쓰는 쉬운 말(08-화면-기본-틀 13장 '화면에 쓰는 말', 요구사항명세 부록 A).
// 저장된 행동 기록 문장은 바꾸지 않아요. 화면에 그릴 때만 바꾸고, 원문은 title로 그대로 볼 수 있어요.
// 상대 미확인은 08·GLOSSARY대로 "확인 없음"으로 보여요(06 부록 A의 "답하지 않았어요"와 달라 08을 따름).
