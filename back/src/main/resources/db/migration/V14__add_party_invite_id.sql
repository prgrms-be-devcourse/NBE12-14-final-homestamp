-- 초대 회차 ID(#437). 초대하거나 번호를 고쳐 다시 초대할 때마다 새로 정한다.
--
-- 받은 초대의 연결·거절은 자리 ID만으로 와서, X → Y → X로 다시 초대하면 예전 초대 화면에서 늦게 온 요청과 새 초대를
-- 구분하지 못한다(#370 활성화 조건 ①). 받은 초대 목록이 이 값을 주고, 연결·거절은 이 값을 함께 보내 지금 초대와 다르면 거절한다.
--
-- 기존 초대됨·거절됨 자리는 지금 회차로 하나씩 채운다. 그 밖의 자리(비어 있음·번호만·연결됨 등)는 비워 둔다.
-- "초대됨이면 회차가 있다"는 DB 제약은 넣지 않는다. 이전 버전 앱(회차를 쓰지 않는 초대)이 블루/그린 전환 중 같은 DB에 초대됨을 적을 수 있어서다
-- (04 8장 "스키마 변경: 이전 버전 앱과도 맞게"). 새 앱은 엔티티에서 회차 없이 초대됨으로 바꾸지 않는다.
-- 이전 버전 앱이 회차 없이 초대한 자리는 새 앱이 자리 ID를 회차로 본다(Party.currentInviteId). 번호를 고쳐 다시 초대하면 새 회차가 생긴다.
ALTER TABLE state.party
    ADD COLUMN invite_id uuid;

UPDATE state.party
SET invite_id = gen_random_uuid()
WHERE status IN ('INVITED', 'REJECTED');
